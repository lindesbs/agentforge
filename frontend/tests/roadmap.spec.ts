import AxeBuilder from '@axe-core/playwright'
import { test, expect } from './fixtures'
import type { Page } from '@playwright/test'

const portable = (content = '# Shared rules\nKeep project overrides visible.\n') => JSON.stringify({format:'agentforge-template',version:1,template:{name:'Imported rules',provider:'codex',kind:'instructions',sourcePath:'AGENTS.md',tags:['portable','team'],content}})
async function openProject(page: Page) {
 await page.goto('/')
 await page.getByLabel('Project directory', {exact:true}).fill('/projects/sample-project')
 await page.getByRole('button',{name:'Inspect project',exact:true}).click()
 await page.getByRole('button',{name:'AGENTS.md',exact:true}).click()
}
async function library(page: Page) { await page.getByRole('button',{name:'Template library',exact:true}).click() }

test('tagged templates are searchable and provider mismatches cannot be applied', async ({page}) => {
 await openProject(page)
 await page.getByText('Configuration templates', {exact:false}).filter({has:page.locator('.count')}).click()
 await page.getByLabel('New template name').fill('Go team rules')
 await page.getByLabel('Tags (optional, comma-separated)').fill('Golang, team')
 await page.getByRole('button',{name:'Save file as template'}).click()
 await library(page)
 await page.getByLabel('Search templates',{exact:true}).fill('golang')
 await expect(page.getByRole('heading',{name:'Go team rules',exact:true})).toBeVisible()
 await expect(page.getByRole('heading',{name:'Team defaults',exact:true})).toBeHidden()
 await page.getByLabel('Provider',{exact:true}).selectOption('claude')
 await expect(page.getByRole('heading',{name:'No matching templates'})).toBeVisible()
 await page.getByRole('button',{name:'Clear template filters'}).click()
 await page.getByRole('button',{name:/^Project configuration/}).click()
 await page.getByRole('button',{name:'.claude/agents/reviewer.md',exact:true}).click()
 await library(page)
 for(const button of await page.getByRole('button',{name:'Load into current file',exact:true}).all()) await expect(button).toBeDisabled()
 await page.getByRole('button',{name:'Export Go team rules',exact:true}).click()
 const output=page.getByLabel('Portable template JSON')
 await expect(output).toBeFocused()
 expect(JSON.parse(await output.inputValue()).template.tags).toEqual(['golang','team'])
 await expect(page.getByText('This export includes the complete native text.',{exact:false})).toBeVisible()
 expect(await page.evaluate(()=>(window as any).__calls)).toEqual(['save-template'])
})

test('import review is read-only, invalidated by edits, and survives navigation', async ({page}) => {
 await page.goto('/');await library(page)
 const input=page.getByLabel('Template JSON to review')
 await input.fill(portable())
 await page.getByRole('button',{name:'Review import',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Review: Imported rules'})).toBeFocused()
 expect(await page.evaluate(()=>(window as any).__calls)).toEqual([])
 await page.getByRole('button',{name:'Learning library',exact:true}).click()
 await library(page)
 await expect(input).toHaveValue(portable())
 await input.fill(portable('# Revised rules'))
 await expect(page.getByRole('button',{name:'Import reviewed template'})).toBeHidden()
 await page.getByRole('button',{name:'Review import',exact:true}).click()
 await page.getByRole('button',{name:'Import reviewed template'}).click()
 await expect(page.getByRole('status')).toContainText('No project files changed')
 await expect(input).toHaveValue('')
 await expect(page.getByRole('heading',{name:'Imported rules',exact:true})).toBeVisible()
 expect(await page.evaluate(()=>(window as any).__calls)).toEqual(['import-template'])
})

test('import errors preserve inputs and pending imports cannot be submitted twice', async ({page}) => {
 await page.goto('/');await library(page)
 await page.getByLabel('Template JSON to review').fill(portable())
 await page.getByRole('button',{name:'Review import',exact:true}).click()
 await page.evaluate(()=>{(window as any).__failImport=true;(window as any).__delayImport=300})
 const submit=page.getByRole('button',{name:'Import reviewed template'})
 await submit.click();await expect(submit).toBeDisabled()
 await expect(page.getByRole('alert')).toContainText('Library is not writable')
 await expect(page.getByLabel('Template JSON to review')).toHaveValue(portable())
 await expect(submit).toBeEnabled()
 await page.evaluate(()=>(window as any).__failImport=false)
 await submit.click()
 await expect(page.getByRole('status')).toContainText('Imported')
 expect(await page.evaluate(()=>(window as any).__calls)).toEqual(['import-template','import-template'])
})

