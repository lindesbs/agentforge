test('new views reflow, support keyboard and pass automated accessibility checks', async ({page},testInfo) => {
 await openProject(page)
 for(const name of ['Template library','Definition map']) {
  await page.getByRole('button',{name,exact:true}).focus();await page.keyboard.press('Enter')
  await expect(page.getByRole('heading',{name,exact:true})).toBeFocused()
  for(const width of [1280,768,320]) {
   await page.setViewportSize({width,height:900})
   await page.evaluate(()=>window.scrollTo(0,0))
   expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
   await page.screenshot({path:testInfo.outputPath(name.replaceAll(' ','-').toLowerCase()+'-'+width+'.png'),fullPage:true})
  }
  const results=await new AxeBuilder({page}).analyze()
  expect(results.violations).toEqual([])
 }
})
