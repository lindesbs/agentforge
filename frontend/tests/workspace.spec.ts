async function openProject(page: Page, file = 'AGENTS.md') {
  await page.goto('/')
  await page.getByLabel('Project directory', { exact: true }).fill('/projects/sample-project')
  await page.getByRole('button', { name: 'Inspect project', exact: true }).click()
  if (file) await page.getByRole('button', { name: file, exact: true }).click()
}

test('workspace comes first; keyboard editing requires review before save', async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Your project, its native configuration.' })).toBeVisible()
  await expect(page.getByLabel('Learning title')).toBeHidden()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Skip to workspace' })).toBeFocused()
  await page.keyboard.press('Enter')
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Project directory', { exact: true })).toBeFocused()
  await page.keyboard.type('/projects/sample-project')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Browse…' })).toBeFocused()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Filter files')).toBeVisible()
  await page.keyboard.press('Tab') // file filter
  await page.keyboard.press('Tab') // Claude agent
  await page.keyboard.press('Tab') // Codex settings
  await page.keyboard.press('Tab') // AGENTS.md
  await expect(page.getByRole('button', { name: 'AGENTS.md', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'AGENTS.md', exact: true })).toBeFocused()
  await page.keyboard.press('Tab') // definition disclosure
  await page.keyboard.press('Tab') // native text
  const source = page.getByLabel('Native configuration', { exact: true })
  await expect(source).toBeFocused()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('workspace-desktop.png'), fullPage: true })
  await page.keyboard.press('Control+End')
  await page.keyboard.type('\nReviewed keyboard change.')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Preview changes', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Review your changes' })).toBeFocused()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('review-desktop.png'), fullPage: true })
  expect(await page.evaluate(() => (window as any).__calls)).toEqual(['preview'])
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Save reviewed changes' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toContainText('Saved.')
  await expect(page.getByText('Matches loaded file')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'AGENTS.md', exact: true })).toBeFocused()
  expect(await page.evaluate(() => (window as any).__calls)).toEqual(['preview', 'preview', 'save'])
})

