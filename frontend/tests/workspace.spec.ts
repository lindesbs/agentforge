test('validation blocks saving and pending save locks editing', async ({ page }) => {
  await openProject(page)
  const source = page.getByLabel('Native configuration', { exact: true })
  await source.fill('INVALID fixture')
  await page.getByRole('button', { name: 'Preview changes', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save reviewed changes' })).toBeDisabled()
  expect(await page.evaluate(() => (window as any).__calls.includes('save'))).toBe(false)
  await source.fill('Valid fixture')
  await page.getByRole('button', { name: 'Preview changes', exact: true }).click()
  await page.evaluate(() => { (window as any).__delaySave = 600 })
  await page.getByRole('button', { name: 'Save reviewed changes' }).click()
  await expect(source).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Saving…', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '.codex/config.toml', exact: true })).toBeDisabled()
  await expect(page.getByText('Matches loaded file')).toBeVisible()
  expect(await page.evaluate(() => (window as any).__calls.filter((call: string) => call === 'save').length)).toBe(1)
})

